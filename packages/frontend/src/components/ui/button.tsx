          "type-control text-icon-primary hover:bg-hover aria-expanded:bg-hover",
        destructive:
          "type-control bg-destructive/10 text-destructive hover:bg-destructive/20 focus-visible:border-destructive/40 focus-visible:ring-destructive/20",
